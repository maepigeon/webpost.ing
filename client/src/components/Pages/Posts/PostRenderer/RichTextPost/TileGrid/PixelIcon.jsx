function flipH(rows) {
  return rows.map(b => { let o = 0; for (let i = 0; i < 8; i++) if (b & (1 << i)) o |= 0x80 >> i; return o; });
}
const flipV = (rows) => rows.slice(0, 7).reverse().concat(rows[7] ? [rows[7]] : [0]);
function transpose(rows) {
  const out = new Array(8).fill(0);
  for (let y = 0; y < 8; y++) for (let x = 0; x < 8; x++) if (rows[y] & (0x80 >> x)) out[x] |= 0x80 >> y;
  return out;
}

// The eight direction arrows, derived from two drawings.
ICONS.arrowLeft = flipH(ICONS.arrowRight);
ICONS.arrowDown = transpose(ICONS.arrowRight);
ICONS.arrowUp = flipV(ICONS.arrowDown);
ICONS.arrowUpLeft = flipH(ICONS.arrowUpRight);
ICONS.arrowDownRight = flipV(ICONS.arrowUpRight);
ICONS.arrowDownLeft = flipH(ICONS.arrowDownRight);

export default function PixelIcon({ name, size = 16 }) {
  const rows = ICONS[name] || ICONS.none;
  const rects = [];
  rows.forEach((bits, y) => {
    for (let x = 0; x < 8; x++) if (bits & (0x80 >> x)) rects.push(<rect key={`${x},${y}`} x={x} y={y} width="1" height="1" />);
  });
  return (
    <svg className="pixel-icon" width={size} height={size} viewBox="0 0 8 8" shapeRendering="crispEdges"
      fill="currentColor" aria-hidden="true" style={{ display: 'block' }}>
      {rects}
    </svg>
  );
}
